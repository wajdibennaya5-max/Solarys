const DICTS = { fr, en, ar };
export const LANGUAGES = [
  { code: 'fr', label: 'Français', dir: 'ltr' },
  { code: 'en', label: 'English', dir: 'ltr' },
  { code: 'ar', label: 'العربية', dir: 'rtl' },
];

let current = 'fr';

export function setLanguage(code) {
  current = DICTS[code] ? code : 'fr';
  const dir = LANGUAGES.find((l) => l.code === current).dir;
  if (typeof document !== 'undefined') {
    document.documentElement.lang = current;
    document.documentElement.dir = dir;
  }
  return current;
}

export const getLanguage = () => current;
export const direction = () => LANGUAGES.find((l) => l.code === current).dir;

/** Traduit une clé ; retombe sur le français puis sur la clé elle-même. */
export function t(key, vars) {
  let s = DICTS[current]?.[key] ?? fr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

/** Locale de formatage des nombres et des dates. */
export const locale = () => ({ fr: 'fr-FR', en: 'en-GB', ar: 'ar-TN' }[current] ?? 'fr-FR');
